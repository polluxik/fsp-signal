import { expect, test } from '@playwright/test'
import { currentUserId, signIn } from './test-support'

test('HR opens six hours and candidate books, shares notes and cancels through the calendar link', async ({ browser }) => {
  const employer = await browser.newPage()
  const candidate = await browser.newPage()
  await signIn(employer, 'employer@demo.test')
  await signIn(candidate, 'backend-middle-4@demo.test')
  const candidateId = await currentUserId(candidate)
  const invitation = await employer.evaluate(async id => {
    const token = decodeURIComponent(document.cookie.split('; ').find(part => part.startsWith('fsp_csrf='))!.split('=')[1])
    const needs = await fetch('/api/v1/employer/needs').then(response => response.json())
    const need = needs.find((item: { specialization: string; grade: string }) => item.specialization === 'backend' && item.grade === 'middle')
    const response = await fetch('/api/v1/employer/invitations', { method: 'POST', headers: {
      'content-type': 'application/json', 'x-csrf-token': token, 'Idempotency-Key': `calendar-browser-${id}` },
      body: JSON.stringify({ candidate_id: id, need_id: need.id, offer_text: 'Обсудим надёжный backend и работу с событиями.',
        reason: 'Стек Python заявлен кандидатом, уточним опыт на разговоре.', salary_min_rub: 200000,
        salary_max_rub: 230000, work_format: 'remote', employer_contact: 'team@demo.test' }) })
    if (!response.ok) throw new Error(await response.text())
    return response.json()
  }, candidateId)
  await candidate.evaluate(async id => {
    const token = decodeURIComponent(document.cookie.split('; ').find(part => part.startsWith('fsp_csrf='))!.split('=')[1])
    const response = await fetch(`/api/v1/invitations/${id}/accept`, { method: 'POST', headers: { 'x-csrf-token': token } })
    if (!response.ok) throw new Error(await response.text())
  }, invitation.id)
  await employer.getByRole('button', { name: 'Календарь HR' }).click()
  await expect(employer.getByRole('heading', { name: 'Календарь HR' })).toBeVisible()
  await employer.getByLabel('Ссылка на созвон', { exact: true }).fill('https://meet.example.test/demo')
  await employer.getByRole('button', { name: 'Сохранить календарь' }).click()
  await expect(employer.getByRole('status')).toContainText('Настройки календаря сохранены')
  await employer.getByRole('button', { name: 'Открыть диапазон' }).click()
  await expect(employer.getByRole('status')).toContainText('Свободные слоты добавлены')
  await expect(employer.locator('.time-cell.available')).toHaveCount(12)
  const calendarUrl = await employer.getByLabel('Ссылка на календарь', { exact: true }).inputValue()
  const screenshot = test.info().outputPath('hr-calendar.png')
  await employer.screenshot({ path: screenshot, fullPage: true })
  console.log('HR calendar screenshot:', screenshot)
  await candidate.goto(calendarUrl)
  await expect(candidate.getByRole('heading', { name: 'Выберите время созвона' })).toBeVisible()
  await candidate.locator('.booking-slots button').first().click()
  await candidate.getByRole('button', { name: 'Подтвердить время' }).click()
  await expect(candidate.getByText('Встреча назначена', { exact: true })).toBeVisible()
  await expect(candidate.getByRole('link', { name: 'Открыть созвон' })).toHaveAttribute('href', 'https://meet.example.test/demo')
  await candidate.getByRole('link', { name: 'В кабинет', exact: true }).click()
  await candidate.getByRole('button', { name: 'Встречи', exact: true }).click()
  const meeting = candidate.getByTestId('meeting-card').first()
  await meeting.getByLabel('Общие заметки и договорённости').fill('Уточнить задачи и следующий этап интервью.')
  await meeting.getByRole('button', { name: 'Сохранить материалы' }).click()
  await expect(meeting.getByRole('status')).toContainText('Материалы сохранены')
  await meeting.getByRole('checkbox', { name: 'Я согласен на хранение записи и расшифровки этой встречи' }).click()
  await expect(meeting.getByRole('status')).toContainText('Согласие сохранено')
  await employer.getByRole('button', { name: 'Обновить встречи' }).click()
  const hrMeeting = employer.getByTestId('meeting-card').first()
  await expect(hrMeeting.getByLabel('Общие заметки и договорённости')).toHaveValue('Уточнить задачи и следующий этап интервью.')
  await hrMeeting.getByRole('checkbox', { name: 'Я согласен на хранение записи и расшифровки этой встречи' }).click()
  await expect(hrMeeting.getByRole('status')).toContainText('Согласие сохранено')
  await candidate.getByRole('button', { name: 'Обновить встречи' }).click()
  await expect(meeting.getByText('Оба участника согласны.', { exact: false })).toBeVisible()
  await meeting.getByRole('button', { name: 'Отменить встречу' }).click()
  await expect(meeting.getByRole('status')).toContainText('Встреча отменена')
  await candidate.goto(calendarUrl)
  await expect(candidate.locator('.booking-slots button')).toHaveCount(12)
  await employer.close(); await candidate.close()
})

test('candidate uses Twinby-style cards with explained match, saves, skips and restores on mobile', async ({ page }) => {
  await signIn(page, 'backend-middle-6@demo.test')
  await page.getByRole('button', { name: 'Карточки', exact: true }).click()
  const card = page.getByTestId('twin-card')
  await expect(card).toBeVisible()
  await expect(card.getByText('Совпадение по профилю', { exact: true })).toBeVisible()
  await card.getByText('Из чего складывается процент', { exact: true }).click()
  await expect(card.locator('.match-components')).toContainText('Описание и задачи')
  await card.getByRole('button', { name: 'Интересно — сохранить ♥', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Роль сохранена')
  await card.focus(); await card.press('ArrowLeft')
  await expect(page.getByRole('status')).toContainText('Роль скрыта')
  await page.getByRole('button', { name: 'Вернуть роль' }).click()
  await expect(page.getByRole('status')).toContainText('Роль возвращена')
  await page.getByLabel('Только сохранённые').check()
  await expect(card).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(card.getByRole('button', { name: 'Интересно — сохранить ♥', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy()
  const screenshot = test.info().outputPath('twin-cards-mobile.png')
  await page.screenshot({ path: screenshot, fullPage: true })
  console.log('Twin cards screenshot:', screenshot)
})
