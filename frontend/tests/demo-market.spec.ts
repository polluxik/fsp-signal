import { expect, test } from '@playwright/test'
import { signIn } from './test-support'

test('HR reads full synthetic CV, compares claims and retains filters and page after reload', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await signIn(page, 'employer@demo.test')
  await page.getByRole('button', { name: 'Рынок', exact: true }).click()
  const market = page.getByTestId('demo-market')
  await expect(market).toContainText('200 резюме · 120 вакансий · 32 направления')
  await expect(market.getByTestId('market-card')).toHaveCount(20)
  await expect(market).not.toContainText(/демо|синтетическ|вымышлен/i)
  for (const width of [1440, 1180, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 920 })
    const layout = await market.getByTestId('market-card').evaluateAll(cards => cards.map(card => {
      const rect = card.getBoundingClientRect()
      const button = card.querySelector('button')!.getBoundingClientRect()
      return { left: rect.left, right: rect.right, top: rect.top, buttonBottom: button.bottom,
        padding: parseFloat(getComputedStyle(card).paddingLeft), viewport: innerWidth }
    }))
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
    for (const card of layout) {
      expect(card.left).toBeGreaterThanOrEqual(0)
      expect(card.right).toBeLessThanOrEqual(card.viewport + 1)
      expect(card.padding).toBeGreaterThanOrEqual(20)
    }
    const firstRow = layout.filter(card => Math.abs(card.top - layout[0].top) < 1)
    expect(Math.max(...firstRow.map(card => card.buttonBottom)) - Math.min(...firstRow.map(card => card.buttonBottom))).toBeLessThanOrEqual(1)
  }
  await page.setViewportSize({ width: 1365, height: 920 })
  await expect(market.getByTestId('market-card').first()).toContainText('Навыки не проверены')
  await market.getByLabel('Направление рынка').selectOption('backend')
  await market.getByLabel('Заявленный уровень').selectOption('junior')
  await market.getByRole('button', { name: 'Применить фильтры' }).click()
  await expect(market.getByTestId('market-card').first()).toHaveAttribute('data-record-id', 'syn-candidate-001')
  await market.getByRole('button', { name: 'Читать резюме' }).first().click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByTestId('market-resume')).toContainText('Кандидат S-001')
  await expect(dialog).not.toContainText(/демо|синтетическ|вымышлен/i)
  await expect(dialog).toContainText('История работы')
  await expect(dialog).toContainText('Рассказ о достижении')
  await expect(dialog).toContainText('Проверка навыков ещё не пройдена')
  await expect(dialog.getByRole('button', { name: /Пригласить/ })).toHaveCount(0)
  await dialog.getByLabel('Вакансия для сравнения').selectOption('syn-vacancy-001')
  const comparison = dialog.getByTestId('market-comparison')
  await expect(comparison).toContainText('это не вероятность найма')
  await expect(comparison).toContainText('Есть расхождения в заявленных условиях')
  await expect(comparison).toContainText('Обязательные навыки — заявлены')
  await expect(dialog).not.toContainText(/демо|синтетическ|вымышлен/i)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('market-resume-mobile.png') })
  await page.getByRole('button', { name: 'Закрыть карточку' }).click()
  await page.reload()
  await expect(page.getByTestId('demo-market')).toBeVisible()
  await expect(market.getByLabel('Направление рынка')).toHaveValue('backend')
  await expect(market.getByLabel('Заявленный уровень')).toHaveValue('junior')
  await market.getByRole('button', { name: 'Сбросить фильтры' }).click()
  await expect(market.getByTestId('market-card')).toHaveCount(20)
  await market.getByRole('button', { name: 'Следующая страница' }).click()
  await expect(market.getByTestId('market-card').first()).toHaveAttribute('data-record-id', 'syn-candidate-021')
  await page.reload()
  await expect(market.getByTestId('market-card').first()).toHaveAttribute('data-record-id', 'syn-candidate-021')
  await market.getByLabel('Навык или текст').fill('несуществующий-навык-xyz')
  await market.getByRole('button', { name: 'Применить фильтры' }).click()
  await expect(market).toContainText('Ничего не найдено')
  await market.getByRole('button', { name: 'Сбросить фильтры' }).click()
  await expect(market.getByTestId('market-card')).toHaveCount(20)
  await page.getByRole('button', { name: 'Найти специалиста', exact: true }).click()
  await page.reload()
  await expect(page.getByTestId('demo-market')).toHaveCount(0)
  expect(errors).toEqual([])
  console.log(`Synthetic resume screenshot: ${testInfo.outputPath('market-resume-mobile.png')}`)
})

test('candidate sees demo vacancies for unsupported assessment families without changing profile or grade', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signIn(page, 'backend-middle-5@demo.test')
  const before = await page.evaluate(async () => (await fetch('/api/v1/candidate/profile')).json())
  await page.getByRole('button', { name: 'Рынок', exact: true }).click()
  const market = page.getByTestId('demo-market')
  await expect(market.getByTestId('market-card')).toHaveCount(20)
  await expect(market.getByRole('button', { name: 'Резюме', exact: true })).toHaveCount(0)
  await market.getByLabel('Направление рынка').selectOption('devops')
  await market.getByLabel('Заявленный уровень').selectOption('lead')
  await market.getByRole('button', { name: 'Применить фильтры' }).click()
  await expect(market.getByTestId('market-card')).toHaveCount(1)
  await expect(market.getByTestId('market-card')).toContainText('Lead — требование роли')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('market-vacancies-mobile.png') })
  await market.getByRole('button', { name: 'Условия вакансии' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByTestId('market-vacancy')).toContainText('Первые 30 дней')
  await expect(dialog).not.toContainText(/демо|синтетическ|вымышлен/i)
  await expect(dialog.getByRole('button', { name: /Отклик|Пригласить/ })).toHaveCount(0)
  const after = await page.evaluate(async () => (await fetch('/api/v1/candidate/profile')).json())
  expect(after).toEqual(before)
  expect(await page.evaluate(async () => (await fetch('/api/v1/demo-market/profiles')).status)).toBe(403)
  console.log(`Synthetic vacancy screenshot: ${testInfo.outputPath('market-vacancies-mobile.png')}`)
})
